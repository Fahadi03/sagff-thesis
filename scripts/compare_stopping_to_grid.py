"""Do the 30 stopping-diagnostic runs equal the corresponding grid runs bit for bit?

The diagnostic runs (results/diagnostics/stopping/) were made before the per-epoch
gate trajectory and the convergence-anchored readout were added to src/train.py;
the grid runs (results/runs/) were made after. If every field the diagnostic logs
contain is identical in the grid logs, then adding those two readouts did not
perturb training. Compared with exact equality: the per-epoch curve (epoch, train
loss, val Macro-F1), best epoch and epochs run, all metrics, and every gate
statistic present in the diagnostic log. Writes results/tables/stopping_vs_grid.md.

Usage:  python scripts/compare_stopping_to_grid.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIAG = ROOT / "results" / "diagnostics" / "stopping"
GRID = ROOT / "results" / "runs"
OUT = ROOT / "results" / "tables" / "stopping_vs_grid.md"
CURVE_FIELDS = ("epoch", "train_loss", "val_macro_f1")


def differences(diag: dict, grid: dict) -> list[str]:
    """Names of the compared fields that are not exactly equal."""
    curve = [{k: c[k] for k in CURVE_FIELDS} for c in diag["training_log"]["curve"]]
    grid_curve = [{k: c[k] for k in CURVE_FIELDS} for c in grid["training_log"]["curve"]]
    out = [] if curve == grid_curve else ["curve"]
    for key in ("best_epoch", "epochs_run"):
        if diag["training_log"][key] != grid["training_log"][key]:
            out.append(key)
    if diag["metrics"] != grid["metrics"]:
        out.append("metrics")
    out += [f"gate.{k}" for k in diag["gate"] if diag["gate"][k] != grid["gate"].get(k)]
    return out


def main() -> None:
    """Compare every diagnostic log with its grid counterpart and write the table."""
    rows, commits = [], set()
    for path in sorted(DIAG.glob("*.json")):
        diag = json.loads(path.read_text(encoding="utf-8"))
        grid = json.loads((GRID / path.name).read_text(encoding="utf-8"))
        commits.add((diag["git"]["commit"][:7], grid["git"]["commit"][:7]))
        rows.append((path.stem, differences(diag, grid)))
    n_same = sum(not d for _, d in rows)
    L = ["# Stopping diagnostic against the grid: reproduction check", "",
         "Generated by `python scripts/compare_stopping_to_grid.py`. Do not edit by hand.", "",
         f"- (diagnostic commit, grid commit): {sorted(commits)}",
         f"- runs compared: {len(rows)}",
         f"- **identical** (per-epoch curve, best and final epoch, all metrics, every gate statistic in "
         f"the diagnostic log; exact equality): {n_same} of {len(rows)}",
         f"- differing: {len(rows) - n_same}"
         + "".join(f"\n  - `{rid}`: {', '.join(d)}" for rid, d in rows if d), ""]
    OUT.write_bytes(("\n".join(L) + "\n").encode("utf-8"))
    print("\n".join(L))


if __name__ == "__main__":
    main()
