"""Freeze baseline-cap's hidden width and tabulate the parameter count of all
four heads -> results/tables/head_capacity.md (and the `heads` section of
configs/default.yaml).

Counts are taken from the instantiated torch modules, not from a formula.

Usage:  python scripts/head_capacity.py
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.features import STATS_DIM, load_feature_dims  # noqa: E402
from src.models import D_MODEL, HEAD_ORDER, build_head, cap_hidden_for, count_params  # noqa: E402

CONFIG = ROOT / "configs" / "default.yaml"
OUT = ROOT / "results" / "tables" / "head_capacity.md"
PRIMARY = "bnintent30-bn"  # the cap is matched on the primary tracks' class count
TOLERANCE = 0.20


def main() -> None:
    dims = load_feature_dims()
    feat_dim = dims["tfidf_dim"] + dims["chargram_dim"] + STATS_DIM
    manifest = json.loads((ROOT / "data" / "splits" / "manifest.json").read_text(encoding="utf-8"))
    n_classes = {t: len(v) for t, v in manifest["label_names"].items()}
    cap_hidden = cap_hidden_for(feat_dim, n_classes[PRIMARY])

    counts = {(h, t): count_params(build_head(h, n_classes[t], feat_dim, cap_hidden))
              for h in HEAD_ORDER for t in ("bnintent30-bn", "banking77")}
    problems = [f"{t}: baseline-cap/sagff = {counts[('baseline-cap', t)] / counts[('sagff', t)]:.3f}"
                for t in ("bnintent30-bn", "banking77")
                if abs(counts[("baseline-cap", t)] / counts[("sagff", t)] - 1) > TOLERANCE]
    if problems:
        sys.exit(f"baseline-cap is not within {TOLERANCE:.0%} of sagff: {problems}")

    L = ["# Head capacity", "", "Generated by `python scripts/head_capacity.py`. Do not edit by hand.", "",
         f"Trainable parameters per head, counted from the instantiated modules. d_model = {D_MODEL}; "
         f"handcrafted feature dimension F = {dims['tfidf_dim']} (tfidf) + {dims['chargram_dim']} "
         f"(chargram) + {STATS_DIM} (stats) = {feat_dim}; baseline-cap hidden width H = {cap_hidden} "
         f"(matched to sagff at {n_classes[PRIMARY]} classes, rounded to a multiple of 64). "
         "Grid order = row order; baseline-cap runs last.", "",
         "| head | uses handcrafted features | params, 30 classes (BNIntent30) | / sagff | "
         "params, 77 classes (BANKING77) | / sagff |", "| --- | --- | --- | --- | --- | --- |"]
    for h in HEAD_ORDER:
        uses = build_head(h, 2, feat_dim, cap_hidden).uses_features
        a, b = counts[(h, "bnintent30-bn")], counts[(h, "banking77")]
        L.append(f"| {h} | {'yes' if uses else 'no'} | {a:,} | {a / counts[('sagff', 'bnintent30-bn')]:.3f} | "
                 f"{b:,} | {b / counts[('sagff', 'banking77')]:.3f} |")
    OUT.write_bytes(("\n".join(L) + "\n").encode("utf-8"))
    print("\n".join(L))

    cfg = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    cfg["heads"] = {
        "order": list(HEAD_ORDER),
        "d_model": D_MODEL,
        "feat_dim": feat_dim,
        "baseline_cap_hidden": cap_hidden,
        "baseline_cap_matching": f"src.models.cap_hidden_for: parameter count matched to sagff at "
                                 f"{n_classes[PRIMARY]} classes, H rounded to a multiple of 64; "
                                 f"must stay within {TOLERANCE:.0%} of sagff",
        "param_counts": {h: {"30_classes": counts[(h, "bnintent30-bn")],
                             "77_classes": counts[(h, "banking77")]} for h in HEAD_ORDER},
    }
    header = CONFIG.read_text(encoding="utf-8").split("\n", 2)
    header = "\n".join(header[:2]) + "\n" if header[0].startswith("#") else ""
    CONFIG.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8", newline="\n")
    print(f"\nwrote {CONFIG.relative_to(ROOT)} (heads section)")


if __name__ == "__main__":
    main()
