"""Freeze the head configuration (cap widths, gate-bias init, dropout) and
tabulate the parameter count of all five heads -> results/tables/head_capacity.md
and the `heads` section of configs/default.yaml.

Counts are taken from the instantiated torch modules, not from a formula.

Usage:  python scripts/head_capacity.py
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.features import STATS_DIM, load_feature_dims  # noqa: E402
from src.models import (D_MODEL, HEAD_ORDER, build_head, cap_hidden_for,  # noqa: E402
                        concat_cap_hidden_for, count_params)

CONFIG = ROOT / "configs" / "default.yaml"
OUT = ROOT / "results" / "tables" / "head_capacity.md"
PRIMARY = "bnintent30-bn"  # baseline-cap is matched at the primary tracks' class count
TOLERANCE = {"baseline-cap": 0.20, "concat-cap": 0.01}
GATE_BIAS_INIT = 0.0   # sigmoid(W_g x + 0): g is approximately 0.5 at initialisation (G1)
DROPOUT = 0.1          # conventional default; not tuned (docs/PROTOCOL.md §2)
FEATURES = {"baseline": "no", "concat": "yes", "sagff": "yes", "concat-cap": "yes", "baseline-cap": "no"}
GATE = {"sagff": "yes"}


def main() -> None:
    dims = load_feature_dims()
    feat_dim = dims["tfidf_dim"] + dims["chargram_dim"] + STATS_DIM
    manifest = json.loads((ROOT / "data" / "splits" / "manifest.json").read_text(encoding="utf-8"))
    n_classes = {t: len(v) for t, v in manifest["label_names"].items()}
    heads_cfg = {
        "order": list(HEAD_ORDER),
        "d_model": D_MODEL,
        "feat_dim": feat_dim,
        "dropout": DROPOUT,
        "gate_bias_init": GATE_BIAS_INIT,
        "gate_bias_init_note": "explicit constant for W_g's bias so g ~ 0.5 at init; W_g weights "
                               "keep PyTorch default init under the run seed",
        "baseline_cap_hidden": cap_hidden_for(feat_dim, n_classes[PRIMARY]),
        "concat_cap_hidden": concat_cap_hidden_for(D_MODEL),
        "matching": {h: f"parameter count within {t:.0%} of sagff (src.models, widths rounded "
                        "to a multiple of 64)" for h, t in TOLERANCE.items()},
    }
    tracks = ("bnintent30-bn", "banking77")
    counts = {(h, t): count_params(build_head(h, n_classes[t], heads_cfg, DROPOUT))
              for h in HEAD_ORDER for t in tracks}
    problems = [f"{h} @ {t}: {counts[(h, t)] / counts[('sagff', t)]:.4f}"
                for h, tol in TOLERANCE.items() for t in tracks
                if abs(counts[(h, t)] / counts[("sagff", t)] - 1) > tol]
    if problems:
        sys.exit(f"capacity matching failed: {problems}")
    heads_cfg["param_counts"] = {h: {"30_classes": counts[(h, "bnintent30-bn")],
                                     "77_classes": counts[(h, "banking77")]} for h in HEAD_ORDER}

    L = ["# Head capacity", "", "Generated by `python scripts/head_capacity.py`. Do not edit by hand.", "",
         f"Trainable parameters per head, counted from the instantiated modules. d_model = {D_MODEL}; "
         f"handcrafted feature dimension F = {dims['tfidf_dim']} (tfidf) + {dims['chargram_dim']} "
         f"(chargram) + {STATS_DIM} (stats) = {feat_dim}; baseline-cap hidden width = "
         f"{heads_cfg['baseline_cap_hidden']} (matched at {n_classes[PRIMARY]} classes); concat-cap "
         f"hidden width = {heads_cfg['concat_cap_hidden']}.", "",
         "Confirmatory comparisons, both at matched capacity: **baseline-cap vs concat-cap** "
         "(does handcrafted information help?) and **concat-cap vs sagff** (does gating help?). "
         "baseline and concat are reference points.", "",
         "| head | handcrafted features | gate | params, 30 classes | / sagff | params, 77 classes | / sagff |",
         "| --- | --- | --- | --- | --- | --- | --- |"]
    for h in ("baseline", "concat", "baseline-cap", "concat-cap", "sagff"):
        a, b = counts[(h, "bnintent30-bn")], counts[(h, "banking77")]
        L.append(f"| {h} | {FEATURES[h]} | {GATE.get(h, 'no')} | {a:,} | "
                 f"{a / counts[('sagff', 'bnintent30-bn')]:.4f} | {b:,} | "
                 f"{b / counts[('sagff', 'banking77')]:.4f} |")
    OUT.write_bytes(("\n".join(L) + "\n").encode("utf-8"))
    print("\n".join(L))

    raw = CONFIG.read_text(encoding="utf-8")
    header = "".join(line + "\n" for line in raw.splitlines() if line.startswith("#"))
    cfg = yaml.safe_load(raw)
    cfg["heads"] = heads_cfg
    text = header + yaml.safe_dump(cfg, sort_keys=False)
    if text == raw:
        print(f"\n{CONFIG.relative_to(ROOT)} heads section unchanged (not rewritten)")
        return
    CONFIG.write_text(text, encoding="utf-8", newline="\n")
    print(f"\nwrote {CONFIG.relative_to(ROOT)} (heads section)")


if __name__ == "__main__":
    main()
