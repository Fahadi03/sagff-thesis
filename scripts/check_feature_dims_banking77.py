"""Task Q: is the frozen F inside BANKING77's own one-SD plateau?

The feature dimensions were selected on the two 30-class BNIntent30 tracks and
applied to BANKING77 (77 classes). This script re-runs the SAME extended grid,
the SAME method (handcrafted branch alone, logistic regression, k-matched
VALIDATION Macro-F1; test never opened) and the SAME one-SD rule on banking77
alone, k in {5, full}, five seeds. It does NOT change the frozen F: it only
reports whether the frozen configuration lies within one SD of BANKING77's best.

At k=full every seed has the identical train and val sets (only the train order
differs, which logistic regression ignores), so each k=full score is computed
once per configuration and reused across seeds; this is checked, not assumed
(the split files' sha256 must agree).

Runs only from a committed tree. Writes results/tables/feature_dim_check_banking77.md
and results/selection/feature_dims_banking77/scores.json.

Usage:  python scripts/check_feature_dims_banking77.py
"""
import itertools
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from select_feature_dims import LR_PARAMS, load_train_val, val_macro_f1  # noqa: E402
from src.features import load_feature_dims  # noqa: E402
from src.train import require_clean_tree  # noqa: E402

TRACK = "banking77"
TFIDF = (128, 256, 512, 1024)
CHARGRAM = (128, 256, 512, 1024, 2048)
KS = ("5", "full")
SEEDS = (13, 42, 87, 100, 2026)
OUT = ROOT / "results" / "tables" / "feature_dim_check_banking77.md"
SCORES = ROOT / "results" / "selection" / "feature_dims_banking77" / "scores.json"


def split_shas(k: str, seed: int) -> tuple:
    m = json.loads((ROOT / "data" / "splits" / "manifest.json").read_text(encoding="utf-8"))
    e = next(e for e in m["splits"] if e["track"] == TRACK and e["k"] == k and e["seed"] == seed)
    return tuple(sorted(e["uids"]["train"])), e["sha256"]["val"]


def main() -> None:
    git = require_clean_tree("check_feature_dims_banking77")
    frozen = load_feature_dims()
    frozen_c = (frozen["tfidf_dim"], frozen["chargram_dim"])
    n_classes = 77
    data = {(k, s): load_train_val(TRACK, k, s) for k in KS for s in SEEDS}
    full_keys = {split_shas("full", s) for s in SEEDS}
    assert len(full_keys) == 1, "k=full train/val content differs between seeds; cannot reuse"

    configs = list(itertools.product(TFIDF, CHARGRAM))
    cell = {}
    for tf, ch in configs:
        dims = {"tfidf_dim": tf, "chargram_dim": ch}
        full_score = val_macro_f1(data[("full", SEEDS[0])], dims, n_classes)
        for s in SEEDS:
            cell[(tf, ch, "5", s)] = val_macro_f1(data[("5", s)], dims, n_classes)
            cell[(tf, ch, "full", s)] = full_score
        print(f"tfidf={tf:4d} chargram={ch:4d} done", flush=True)

    seed_score = {(c, s): statistics.mean(cell[c + (k, s)] for k in KS) for c in configs for s in SEEDS}
    mean = {c: statistics.mean(seed_score[(c, s)] for s in SEEDS) for c in configs}
    best = max(configs, key=lambda c: mean[c])
    sd = statistics.stdev([seed_score[(best, s)] for s in SEEDS])
    threshold = mean[best] - sd
    eligible = [c for c in configs if mean[c] >= threshold]
    inside = frozen_c in eligible

    SCORES.parent.mkdir(parents=True, exist_ok=True)
    SCORES.write_text(json.dumps({"git": git, "lr_params": LR_PARAMS, "cells": [
        {"tfidf_dim": k[0], "chargram_dim": k[1], "k": k[2], "seed": k[3], "val_macro_f1": v}
        for k, v in sorted(cell.items())]}, indent=1) + "\n", encoding="utf-8", newline="\n")

    L = ["# Feature dimensions: BANKING77 plateau check (Task Q)", "",
         "Generated by `python scripts/check_feature_dims_banking77.py`. Do not edit by hand.", "",
         f"Run from commit `{git['commit']}` (clean tree). Same method and rule as "
         "`feature_dim_selection.md` (handcrafted branch alone, logistic regression, k-matched "
         f"VALIDATION Macro-F1, test never opened), on `{TRACK}` alone, k in {list(KS)}, seeds "
         f"{list(SEEDS)}. This check does NOT select anything; it asks whether the frozen "
         f"configuration tfidf_dim={frozen_c[0]}, chargram_dim={frozen_c[1]} lies inside "
         "BANKING77's own one-SD plateau.", "",
         f"- BANKING77 best: tfidf_dim={best[0]}, chargram_dim={best[1]}, mean {mean[best]:.4f}",
         f"- SD over seeds of best: {sd:.4f}; threshold {threshold:.4f}",
         f"- frozen configuration: mean {mean[frozen_c]:.4f} -> **"
         + ("INSIDE" if inside else "OUTSIDE") + "** BANKING77's one-SD plateau "
         f"({len(eligible)} of {len(configs)} configurations are inside)", "",
         "| tfidf_dim | chargram_dim | k=5 | k=full | mean | within 1 SD | |",
         "| --- | --- | --- | --- | --- | --- | --- |"]
    for c in configs:
        v5 = [cell[c + ("5", s)] for s in SEEDS]
        tag = "**frozen**" if c == frozen_c else ("best" if c == best else "")
        L.append(f"| {c[0]} | {c[1]} | {statistics.mean(v5):.3f} ({min(v5):.3f}-{max(v5):.3f}) | "
                 f"{cell[c + ('full', SEEDS[0])]:.3f} | {mean[c]:.4f} | "
                 f"{'yes' if c in eligible else 'no'} | {tag} |")
    OUT.write_bytes(("\n".join(L) + "\n").encode("utf-8"))
    print("\n".join(L))


if __name__ == "__main__":
    main()
