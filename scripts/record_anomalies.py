"""Record run anomalies -> results/runs_anomalies.md (generated, never hand-edited; R8).

An anomaly is recorded, never corrected: run JSONs are not edited. The machine-
readable block at the end of runs_anomalies.md is what src/analysis.py reads to
decide which run is excluded from WHICH table (here: timing tables only).

Anomaly 1: a run whose wall_clock_s contains a Windows sleep. The sleep window is
read from the Windows System event log (Kernel-Power event 42 = entering sleep;
Power-Troubleshooter event 1 = resumed from sleep), and the per-step time with
the sleep removed is computed from the run's own JSON.

Usage:  python scripts/record_anomalies.py
"""
import datetime
import json
import statistics
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "runs"
OUT = ROOT / "results" / "runs_anomalies.md"
RUN_ID = "banking77__kfull__seed2026__sagff-noise-perepoch"
PEERS = "banking77__kfull__seed*__sagff-noise-perepoch.json"


def events(day: str) -> list[dict]:
    ps = ("Get-WinEvent -FilterHashtable @{LogName='System'; "
          "ProviderName='Microsoft-Windows-Kernel-Power','Microsoft-Windows-Power-Troubleshooter'; "
          f"StartTime=[datetime]'{day}'; EndTime=([datetime]'{day}').AddDays(1)}} -ErrorAction SilentlyContinue | "
          "Select-Object @{n='t';e={$_.TimeCreated.ToString('yyyy-MM-dd HH:mm:ss')}}, Id, ProviderName | "
          "ConvertTo-Json")
    out = subprocess.run(["powershell", "-NoProfile", "-Command", ps], capture_output=True, text=True).stdout
    data = json.loads(out) if out.strip() else []
    return data if isinstance(data, list) else [data]


def rerun_line() -> str:
    """Evidence from scripts/rerun_anomaly.py, if it has been run."""
    p = ROOT / "results" / "diagnostics" / f"anomaly_rerun_{RUN_ID}.json"
    if not p.exists():
        return "- Re-run evidence: not yet produced (`python scripts/rerun_anomaly.py ...`)."
    r = json.loads(p.read_text(encoding="utf-8"))
    verdict = "**bit-identical on every compared field**" if r["all_identical"] else "**NOT identical**"
    return (f"- Re-run evidence (`scripts/rerun_anomaly.py`, from commit `{r['rerun_git']['commit'][:7]}`, "
            f"the stored run's commit being `{r['stored_commit'][:7]}`): {verdict} - "
            + "; ".join(f"{k}: {'identical' if v else 'DIFFERENT'}" for k, v in r["checks"].items())
            + f". The re-run took {r['rerun_wall_clock_s']} s of wall time without a sleep.")


def steps(log: dict) -> int:
    n = log["splits"]["sizes"]["train"]
    bs = log["config"]["training"]["batch_size"]
    return log["training_log"]["epochs_run"] * (-(-n // bs))


def main() -> None:
    log = json.loads((RUNS / f"{RUN_ID}.json").read_text(encoding="utf-8"))
    day = "2026-10-12"
    ev = events(day)
    sleep = [e for e in ev if e["ProviderName"] == "Microsoft-Windows-Kernel-Power" and e["Id"] == 42]
    wake = [e for e in ev if e["ProviderName"] == "Microsoft-Windows-Power-Troubleshooter" and e["Id"] == 1]
    fmt = "%Y-%m-%d %H:%M:%S"
    # the grid log gives the run's start and end; pick the sleep/wake pair inside it
    grid = (ROOT / "logs" / "grid.log").read_text(encoding="utf-8", errors="replace").splitlines()
    end_line = next(line for line in grid if f"] {RUN_ID}:" in line)
    end = datetime.datetime.strptime(end_line[:19], fmt)
    start = end - datetime.timedelta(seconds=log["wall_clock_s"])
    s_in = [datetime.datetime.strptime(e["t"], fmt) for e in sleep]
    w_in = [datetime.datetime.strptime(e["t"], fmt) for e in wake]
    s0 = min(t for t in s_in if start <= t <= end)
    w0 = min(t for t in w_in if s0 < t <= end)
    slept = (w0 - s0).total_seconds()
    st = steps(log)
    awake_ms = 1000 * (log["wall_clock_s"] - slept) / st
    peers = [json.loads(p.read_text(encoding="utf-8")) for p in RUNS.glob(PEERS) if p.stem != RUN_ID]
    peer_ms = [1000 * p["wall_clock_s"] / steps(p) for p in peers]

    record = {"run_id": RUN_ID, "exclude_from": ["timing"],
              "reason": "wall_clock_s includes a Windows sleep; computation suspended, not altered",
              "logged_wall_clock_s": log["wall_clock_s"],
              "sleep_window": [s0.strftime(fmt), w0.strftime(fmt)], "sleep_seconds": slept,
              "optimizer_steps": st, "ms_per_step_excluding_sleep": round(awake_ms, 2),
              "peer_ms_per_step": [round(x, 2) for x in sorted(peer_ms)]}
    L = ["# Run anomalies", "",
         "Generated by `python scripts/record_anomalies.py`. Do not edit by hand. Anomalies are "
         "RECORDED here, never corrected in the run JSONs (R8). `src/analysis.py` reads the "
         "machine-readable block at the end to exclude a run from the named tables only.", "",
         f"## 1. `{RUN_ID}`", "",
         f"- Logged `wall_clock_s`: {log['wall_clock_s']} (status `{log['status']}`).",
         f"- Run span from `logs/grid.log`: {start.strftime(fmt)} to {end.strftime(fmt)} (local time).",
         f"- Windows sleep inside that span, from the Windows System event log: entered sleep "
         f"{s0.strftime(fmt)} (Microsoft-Windows-Kernel-Power, event 42), resumed "
         f"{w0.strftime(fmt)} (Microsoft-Windows-Power-Troubleshooter, event 1): {slept:.0f} s.",
         f"- Measured per-step time with the sleep removed: ({log['wall_clock_s']} - {slept:.0f}) s / "
         f"{st} optimizer steps = **{awake_ms:.2f} ms/step**, against "
         f"{min(peer_ms):.2f}-{max(peer_ms):.2f} ms/step (mean {statistics.mean(peer_ms):.2f}) for the "
         f"other {len(peer_ms)} seeds of the same cell.",
         "- **Conclusion:** the computation was suspended, not altered. The figure is unusable as "
         "timing only; the run's metrics, gate statistics and pre-specified analyses are fully "
         "included.",
         rerun_line(),
         "", "## Machine-readable exclusions", "", "```json",
         json.dumps([record], indent=1), "```", ""]
    OUT.write_bytes("\n".join(L).encode("utf-8"))
    print("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
