"""§12 extension, step 4: the registered analysis of the Spanish and Hindi runs.

Reads results/extension/runs/ (the 80 extension runs) and, read-only, the en and bn
runs in results/runs/. Writes NEW tables only (results/tables/T8_*); no existing table,
figure or run is touched (src.analysis reads only results/runs/).

  E1 (primary, per language): paired test Macro-F1 difference sagff - baseline over
     k in {5, 10} x 5 seeds (n = 10), two-sided Wilcoxon (zeros dropped), Holm over the
     2 languages, alpha 0.05; observed direction by the §11 item 4 rule; registered
     interpretation of the joint pattern.                         -> T8a_extension_e1.md
  E2 (descriptive): Spearman rho(k rank, sagff gate displacement at the selected
     epoch) per language, n = 20; en and bn shown for reference.    -> T8b_extension_e2.md
  E3 (descriptive): baseline test Macro-F1 at k = 5 for es, hi, en, bn. -> T8c_extension_e3.md
  Descriptive per-k Macro-F1 of both heads for en, bn, es, hi.       -> T8d_extension_macro_f1.md
  Rescoring sensitivity (§12 amendment 2026-11-09): test rows colliding with the run's
     own training subset removed from scoring, same models and predictions; E1
     recomputed if any collision exists, else "not applicable".  -> T8e_extension_rescoring.md

Usage (from the repository root):  python scripts/extension_analysis.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.analysis import ALPHA, fmt_p, holm, msd, observed, spearman, wilcoxon  # noqa: E402
from src.extension import (E1_KS, HEADS, K_RANK, KS, LANGS, RUN_DIR, SEEDS, SPLIT_BASE, TRACK,  # noqa: E402
                           colliding_test_uids, read_jsonl)
from src.train import macro_f1_acc  # noqa: E402

TABLES = ROOT / "results" / "tables"
MAIN_RUNS = ROOT / "results" / "runs"
ALL = ("en", "bn") + LANGS
TRACK_OF = {"en": "bnintent30-en", "bn": "bnintent30-bn", **TRACK}
EXPECTATION = {"es": "not significantly positive", "hi": None}
HEADER = ("Generated by `python scripts/extension_analysis.py`. Do not edit by hand. docs/PROTOCOL.md §12 "
          "(post-registration extension, registered before any run; amendments 2026-11-09 and 2026-11-10). "
          "es and hi are translations written by Claude from English and not reviewed; bn is the dataset's "
          "Google translation reviewed by its authors.")


def load_runs() -> tuple[dict, list[dict]]:
    """{(lang, k, seed, head): log} for ok runs, and every extension log (for accounting)."""
    R, ext = {}, []
    for p in sorted(RUN_DIR.glob("*.json")):
        log = json.loads(p.read_text(encoding="utf-8"))
        if log["spec"]["track"] not in {TRACK[lang] for lang in LANGS}:
            continue                     # other extension tracks (bn-cl) have their own analysis
        ext.append(log)
        if log["status"] == "ok":
            lang = log["spec"]["track"].rsplit("-", 1)[1]
            R[(lang, log["spec"]["k"], log["spec"]["seed"], log["spec"]["condition"])] = log
    for lang in ("en", "bn"):
        for k in KS:
            for s in SEEDS:
                for h in HEADS:
                    p = MAIN_RUNS / f"{TRACK_OF[lang]}__k{k}__seed{s}__{h}.json"
                    log = json.loads(p.read_text(encoding="utf-8"))
                    if log["status"] == "ok":
                        R[(lang, k, s, h)] = log
    return R, ext


def f1(log: dict) -> float:
    return log["metrics"]["test"]["macro_f1"]


def disp(log: dict) -> float:
    return log["gate"]["gate_displacement"]["mean"]


def e1_rows(score) -> list[dict]:
    """E1 for each extension language with `score(lang, k, seed, head)`; Holm over the 2 languages."""
    res = []
    for lang in LANGS:
        x = [score(lang, k, s, "sagff") for k in E1_KS for s in SEEDS]
        y = [score(lang, k, s, "baseline") for k in E1_KS for s in SEEDS]
        res.append({"lang": lang, **wilcoxon(x, y)})
    for r, ph in zip(res, holm([r["p"] for r in res], m=len(res))):
        r["holm"] = ph
        r["observed"] = observed(r)
        r["sig_pos"] = ph < ALPHA and r["observed"] == "> 0"
    return res


def interpretation(res: list[dict]) -> str:
    """The registered interpretation of the joint E1 pattern (§12)."""
    pos = {r["lang"]: r["sig_pos"] for r in res}
    if pos["es"] and pos["hi"]:
        return ("es and hi both significantly positive: consistent with a translation artefact (§12 amendment "
                "2026-11-10: an artefact of translated text, not of one shared translation system).")
    if pos["hi"] and not pos["es"]:
        return "hi significantly positive, es not: consistent with a lower-resource-language effect."
    if not pos["es"] and not pos["hi"]:
        return ("Neither significantly positive: the Bangla gain is not explained by translation or by a general "
                "lower-resource effect.")
    return "es significantly positive and hi not: a pattern without a registered interpretation; reported as observed."


def e1_table(res: list[dict]) -> list[str]:
    L = ["| language | n pairs | n non-zero | W | median paired difference | rank-biserial | p | Holm p (m=2) "
         "| observed direction | significantly positive | registered expectation | expectation |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in res:
        exp = EXPECTATION[r["lang"]]
        met = "none registered" if exp is None else ("met" if not r["sig_pos"] else "not met")
        L.append(f"| {r['lang']} | {r['n']} | {r['n_nonzero']} | {r['statistic']:.1f} | {r['median_diff']:+.4f} | "
                 f"{r['rank_biserial']:+.3f} | {fmt_p(r['p'])} | {fmt_p(r['holm'])} | {r['observed']} | "
                 f"{'yes' if r['sig_pos'] else 'no'} | {exp or 'no directional expectation'} | {met} |")
    return L


def write(name: str, lines: list[str]) -> None:
    (TABLES / name).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote results/tables/{name}")


def main() -> None:
    R, ext = load_runs()
    expected = len(LANGS) * len(HEADS) * len(KS) * len(SEEDS)
    n_ok = sum(l["status"] == "ok" for l in ext)
    n_failed = sum(l["status"] == "failed" for l in ext)
    missing = [(lang, k, s, h) for lang in LANGS for h in HEADS for k in KS for s in SEEDS
               if (lang, k, s, h) not in R]
    if missing:
        sys.exit(f"STOP: {len(missing)} of {expected} extension runs missing or failed, e.g. {missing[:3]}")
    wall = sum(l["wall_clock_s"] for l in ext)
    accounting = (f"Runs: {len(ext)} extension runs in `results/extension/runs/` ({n_ok} ok, {n_failed} failed; "
                  f"{expected} registered), summed run wall-clock {wall / 60:.1f} min. en and bn runs are read from "
                  "`results/runs/` and are unchanged.")

    # E1 -------------------------------------------------------------------------- #
    res = e1_rows(lambda lang, k, s, h: f1(R[(lang, k, s, h)]))
    write("T8a_extension_e1.md", [
        "# T8a. Extension E1 (primary): sagff - baseline test Macro-F1, k in {5, 10}", "", HEADER, "", accounting, "",
        "Paired over (k, seed) for k in {5, 10} and seeds 13, 42, 87, 100, 2026 (n = 10 per language); two-sided "
        "Wilcoxon signed-rank (`scipy.stats.wilcoxon`, zero_method='wilcox'); Holm adjustment over the 2 languages "
        "(a family of its own, separate from §10's); alpha 0.05. Observed direction: sign of the matched-pairs "
        "rank-biserial correlation, 'ambiguous' if the median paired difference has the other sign (§11 item 4). "
        "Significantly positive: Holm p < 0.05 with a positive observed direction.", ""]
        + e1_table(res) + ["", "**Registered interpretation (§12):** " + interpretation(res)])

    # E2 -------------------------------------------------------------------------- #
    L = ["# T8b. Extension E2 (descriptive): Spearman rho(k, sagff gate displacement)", "", HEADER, "",
         "Gate displacement at the epoch selected by early stopping (the primary readout of §10), sagff head, "
         "test split; k as ranks 5 < 10 < 20 < full; n = 20 per language. Not part of any test family. en and bn "
         "are S1 of the main grid, recomputed here for reference. Right: mean ± SD of the displacement over seeds.",
         "", "| language | n | rho | p (unadjusted) | k=5 | k=10 | k=20 | k=full |",
         "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for lang in ALL:
        xs = [K_RANK[k] for k in KS for s in SEEDS]
        ys = [disp(R[(lang, k, s, "sagff")]) for k in KS for s in SEEDS]
        r = spearman(xs, ys)
        L.append(f"| {lang}{' (reference)' if lang in ('en', 'bn') else ''} | {r['n']} | {r['rho']:+.3f} | "
                 f"{fmt_p(r['p'])} | " + " | ".join(msd([disp(R[(lang, k, s, 'sagff')]) for s in SEEDS], "{:+.4f}")
                                                     for k in KS) + " |")
    write("T8b_extension_e2.md", L)

    # E3 -------------------------------------------------------------------------- #
    L = ["# T8c. Extension E3 (descriptive): baseline test Macro-F1 at k = 5", "", HEADER, "",
         "The encoder-only `baseline` head at k = 5, mean ± SD (min-max) over the five seeds. es and hi: extension "
         "runs; en and bn: the main grid (unchanged).", "",
         "| language | baseline Macro-F1, k=5 | min-max | source |", "| --- | --- | --- | --- |"]
    for lang in ("es", "hi", "en", "bn"):
        v = [f1(R[(lang, "5", s, "baseline")]) for s in SEEDS]
        L.append(f"| {lang} | {msd(v)} | {min(v):.3f}-{max(v):.3f} | "
                 f"{'results/extension/runs/' if lang in LANGS else 'results/runs/'} |")
    write("T8c_extension_e3.md", L)

    # descriptive per-k table -------------------------------------------------------- #
    L = ["# T8d. Extension (descriptive): test Macro-F1 of baseline and sagff per k", "", HEADER, "",
         "Mean ± SD over the five seeds; difference paired by seed (sagff - baseline), with the number of seeds "
         "(of 5) in which it is positive. Descriptive: per-cell tests cannot reach alpha 0.05 with five pairs.", "",
         "| language | k | baseline | sagff | sagff - baseline | seeds positive |",
         "| --- | --- | --- | --- | --- | --- |"]
    for lang in ALL:
        for k in KS:
            b = [f1(R[(lang, k, s, "baseline")]) for s in SEEDS]
            g = [f1(R[(lang, k, s, "sagff")]) for s in SEEDS]
            d = [x - y for x, y in zip(g, b)]
            L.append(f"| {lang} | {k} | {msd(b)} | {msd(g)} | {msd(d, '{:+.3f}')} | {sum(v > 0 for v in d)} |")
    write("T8d_extension_macro_f1.md", L)

    # rescoring sensitivity ------------------------------------------------------------ #
    manifest = json.loads((SPLIT_BASE / "manifest.json").read_text(encoding="utf-8"))
    entry = {(e["track"], e["k"], e["seed"]): e for e in manifest["splits"]}
    n_classes = len(next(iter(manifest["label_names"].values())))
    rescored, n_coll = {}, {}
    for lang in LANGS:
        for k in KS:
            for s in SEEDS:
                e = entry[(TRACK[lang], k, s)]
                base = SPLIT_BASE / e["path"]
                train = read_jsonl(base / "train.jsonl")
                test = read_jsonl(base / "test.jsonl")
                coll = set(colliding_test_uids([r["text"] for r in train], [(r["uid"], r["text"]) for r in test]))
                n_coll[(lang, k, s)] = len(coll)
                keep = [r for r in test if r["uid"] not in coll]
                for h in HEADS:
                    pred = R[(lang, k, s, h)]["metrics"]["test"]["predictions"]
                    assert set(pred) == {r["uid"] for r in test}
                    rescored[(lang, k, s, h)] = macro_f1_acc([r["label_id"] for r in keep],
                                                             [pred[r["uid"]] for r in keep], n_classes)["macro_f1"]
    L = ["# T8e. Extension: rescoring sensitivity analysis (§12 amendment 2026-11-09)", "", HEADER, "",
         "A test row collides if its §3.3 dedup key, on that language's text, equals the key of any row in the "
         "run's own training subset. Sensitivity analysis: the same trained models and their saved predictions; "
         "test Macro-F1 recomputed without the colliding rows; E1 recomputed on these scores with the same test and "
         "Holm family. No model is retrained. Applicable to a language only if at least one run has a colliding "
         "test row.", "",
         "Colliding test rows per run, mean (min-max) over seeds (test split: 856 rows):", "",
         "| language | k=5 | k=10 | k=20 | k=full |", "| --- | --- | --- | --- | --- |"]
    for lang in LANGS:
        L.append(f"| {lang} | " + " | ".join(
            f"{np.mean([n_coll[(lang, k, s)] for s in SEEDS]):.1f} ({min(n_coll[(lang, k, s)] for s in SEEDS)}-"
            f"{max(n_coll[(lang, k, s)] for s in SEEDS)})" for k in KS) + " |")
    applicable = {lang: any(n_coll[(lang, k, s)] for k in KS for s in SEEDS) for lang in LANGS}
    L += [""]
    if not any(applicable.values()):
        L.append("No colliding test row in any run of either language: the sensitivity analysis is not applicable.")
    else:
        rres = e1_rows(lambda lang, k, s, h: rescored[(lang, k, s, h)])
        L += ["E1 on the rescored Macro-F1 (same test, n and Holm family as T8a):", ""] + e1_table(rres)
        for lang in LANGS:
            if not applicable[lang]:
                L.append(f"\n{lang}: no colliding test row in any run; its rescored scores equal the original "
                         "scores (rescoring not applicable).")
        L += ["", "**Registered interpretation on the rescored scores:** " + interpretation(rres)]
    write("T8e_extension_rescoring.md", L)


if __name__ == "__main__":
    main()
