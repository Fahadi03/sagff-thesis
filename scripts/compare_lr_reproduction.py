"""Learning-rate reproduction check: do the selection runs from the committed tree
reproduce the earlier runs (made from an uncommitted tree) bit for bit?

Compares every run present in both results/selection/lr_218bd44_uncommitted/
and results/selection/lr/ on everything that training produced: the full
per-epoch curve (train loss and val Macro-F1), the best and final epoch, and
all val / val_full metrics. Floats are compared exactly (==), not approximately.
Writes results/tables/lr_reproduction.md.

Usage:  python scripts/compare_lr_reproduction.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OLD = ROOT / "results" / "selection" / "lr_218bd44_uncommitted"
NEW = ROOT / "results" / "selection" / "lr"
OUT = ROOT / "results" / "tables" / "lr_reproduction.md"


def fingerprint(log: dict) -> dict:
    return {"curve": log["training_log"]["curve"],
            "best_epoch": log["training_log"]["best_epoch"],
            "epochs_run": log["training_log"]["epochs_run"],
            "val": log["metrics"]["val"],
            "val_full_diagnostic": log["metrics"]["val_full_diagnostic"]}


def main() -> None:
    old = {p.name: json.loads(p.read_text(encoding="utf-8")) for p in OLD.glob("*.json")}
    new = {p.name: json.loads(p.read_text(encoding="utf-8")) for p in NEW.glob("*.json")}
    common = sorted(old.keys() & new.keys())
    differ = [n for n in common if fingerprint(old[n]) != fingerprint(new[n])]
    commits_old = sorted({(v["git"]["commit"][:7], v["git"]["working_tree_dirty"]) for v in old.values()})
    commits_new = sorted({(v["git"]["commit"][:7], v["git"]["working_tree_dirty"]) for v in new.values()})
    L = ["# Learning-rate selection: reproduction check", "",
         "Generated by `python scripts/compare_lr_reproduction.py`. Do not edit by hand.", "",
         f"- earlier runs: {len(old)} logs, (commit, dirty tree) = {commits_old}",
         f"- re-runs: {len(new)} logs, (commit, dirty tree) = {commits_new}",
         f"- runs present in both: {len(common)}",
         f"- **identical bit for bit** (full per-epoch curve, best and final epoch, all val and "
         f"val_full metrics, compared with exact float equality): {len(common) - len(differ)} of {len(common)}",
         f"- differing: {len(differ)}" + (f" - {differ[:10]}" if differ else ""), ""]
    OUT.write_bytes(("\n".join(L) + "\n").encode("utf-8"))
    print("\n".join(L))


if __name__ == "__main__":
    main()
