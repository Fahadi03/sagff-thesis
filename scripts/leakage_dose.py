"""Leakage dose per regime (Stage 1b, Task A) -> results/tables/leakage_dose.md

For bnintent30-bn, every k and seed, counts
  (i)  test rows whose normalized key appears in that run's train split
  (ii) test rows whose normalized key appears in that run's k-matched val split
in the dirty (leaky) condition, with the clean condition alongside as a control
(it must be 0 everywhere). Mean and range are across the five seeds.

Usage:  python scripts/leakage_dose.py
"""
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.data import norm_key  # noqa: E402

TRACK = "bnintent30-bn"
KS = ("5", "10", "20", "full")
OUT = ROOT / "results" / "tables" / "leakage_dose.md"
BASES = {"dirty": ROOT / "data" / "splits_dirty", "clean": ROOT / "data" / "splits"}


def keys(path: Path) -> list[str]:
    return [norm_key(json.loads(line)["text"]) for line in path.read_text(encoding="utf-8").splitlines()]


def dose(base: Path, k: str, seed: int) -> dict:
    d = base / TRACK / f"k{k}_seed{seed}"
    test = keys(d / "test.jsonl")
    train, val = set(keys(d / "train.jsonl")), set(keys(d / "val.jsonl"))
    return {"n_test": len(test), "train": sum(t in train for t in test),
            "val": sum(t in val for t in test)}


def summary(xs: list[int]) -> str:
    return f"{statistics.mean(xs):.1f} ({min(xs)}-{max(xs)})"


def main() -> None:
    manifest = json.loads((BASES["dirty"] / "manifest.json").read_text(encoding="utf-8"))
    seeds = manifest["seeds"]
    rows = {c: {k: [dose(b, k, s) for s in seeds] for k in KS} for c, b in BASES.items()}
    n_test = {c: rows[c]["5"][0]["n_test"] for c in BASES}
    L = ["# Leakage dose by regime",
         "",
         "Generated by `python scripts/leakage_dose.py`. Do not edit by hand.",
         "",
         f"Track `{TRACK}`. A test row is *contaminated* when its normalized key "
         "(`src.data.norm_key`) also occurs in the run's train split (i) or in its k-matched "
         f"validation split (ii). Values are mean (min-max) over seeds {seeds}. Dirty = "
         "official assignment after step 1, steps 2-4 not applied "
         f"({n_test['dirty']} test rows). Clean = after §3.3 ({n_test['clean']} test rows); "
         "it is the control and must be 0.",
         "",
         "| k | dirty (i) test rows with key in train | % of test | dirty (ii) test rows with key "
         "in k-matched val | clean (i) | clean (ii) |",
         "| --- | --- | --- | --- | --- | --- |"]
    for k in KS:
        d, c = rows["dirty"][k], rows["clean"][k]
        tr = [x["train"] for x in d]
        L.append(f"| {k} | {summary(tr)} | {100 * statistics.mean(tr) / n_test['dirty']:.1f}% | "
                 f"{summary([x['val'] for x in d])} | {summary([x['train'] for x in c])} | "
                 f"{summary([x['val'] for x in c])} |")
    L += ["", "Per seed, dirty condition (i) / (ii):", "",
          "| k | " + " | ".join(f"seed {s}" for s in seeds) + " |",
          "| --- |" + " --- |" * len(seeds)]
    for k in KS:
        L.append(f"| {k} | " + " | ".join(f"{x['train']} / {x['val']}" for x in rows["dirty"][k]) + " |")
    OUT.write_bytes(("\n".join(L) + "\n").encode("utf-8"))
    print("\n".join(L))


if __name__ == "__main__":
    main()
