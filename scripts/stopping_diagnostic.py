"""Stopping-point diagnostic: does the gate depend on WHICH epoch is kept?

sagff, all three tracks, k in {5, full}, all five seeds (mean and range, never a
single seed - R8). For each run, compares the gate at the selected best epoch
(the one the paper uses) with the gate at the final trained epoch, and records
when training loss first falls below 0.01.

Logs go to results/diagnostics/stopping/ (not results/runs/). Runs only from a
committed tree. Writes results/tables/stopping_diagnostic.md.

Usage:  python scripts/stopping_diagnostic.py
"""
import json
import statistics
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.analysis import n5_note  # noqa: E402
from src.train import CONFIG, RunSpec, require_clean_tree, run  # noqa: E402

TRACKS = ("bnintent30-bn", "bnintent30-en", "banking77")
KS = ("5", "full")
SEEDS = (13, 42, 87, 100, 2026)
LOG_DIR = ROOT / "results" / "diagnostics" / "stopping"
OUT = ROOT / "results" / "tables" / "stopping_diagnostic.md"
LOSS_ZERO = float(yaml.safe_load(CONFIG.read_text(encoding="utf-8"))["training"]["converged_loss_threshold"])


def agg(vals, fmt="{:.4f}") -> str:
    return f"{fmt.format(statistics.mean(vals))} ({fmt.format(min(vals))} to {fmt.format(max(vals))})"


def main() -> None:
    git = require_clean_tree("stopping_diagnostic")
    rows, run_commits = [], set()
    for t in TRACKS:
        for k in KS:
            logs = []
            for s in SEEDS:
                spec = RunSpec(track=t, k=k, seed=s, condition="sagff", log_dir=LOG_DIR)
                path = LOG_DIR / f"{spec.run_id}.json"
                log = json.loads(path.read_text(encoding="utf-8")) if path.exists() else run(spec)
                if log["status"] != "ok":
                    sys.exit(f"{spec.run_id} failed:\n{log.get('traceback')}")
                logs.append(log)
                run_commits.add((log["git"]["commit"], log["git"]["working_tree_dirty"]))
            g = [x["gate"] for x in logs]
            first_zero = []
            for x in logs:
                e = next((c["epoch"] for c in x["training_log"]["curve"] if c["train_loss"] < LOSS_ZERO), None)
                first_zero.append(e if e is not None else float("nan"))
            rows.append({
                "track": t, "k": k,
                "best_epoch": [x["training_log"]["best_epoch"] for x in logs],
                "final_epoch": [x["training_log"]["epochs_run"] for x in logs],
                "loss_zero_epoch": first_zero,
                "disp_best": [y["gate_displacement"]["mean"] for y in g],
                "disp_final": [y["gate_displacement_final_epoch"]["mean"] for y in g],
                "diff": [y["gate_displacement_final_epoch"]["best_minus_final_gate_mean"] for y in g],
                "abs_dim_best": [y["gate_displacement"]["mean_abs_per_dim"] for y in g],
                "abs_dim_final": [y["gate_displacement_final_epoch"]["mean_abs_per_dim"] for y in g],
            })
            print(f"{t} k={k} done", flush=True)

    L = ["# Stopping-point diagnostic: gate at the best epoch vs the final epoch", "",
         "Generated by `python scripts/stopping_diagnostic.py`. Do not edit by hand.", "",
         "Runs produced at commit(s) " + ", ".join(
             f"`{c}`" + (" (DIRTY tree)" if d else " (clean tree)") for c, d in sorted(run_commits))
         + f"; table generated at commit `{git['commit']}`. Head `sagff`; mean (min to max) over seeds "
         f"{list(SEEDS)}. Displacement = gate mean on the test split minus the gate mean at "
         "initialisation. 'Best' = the epoch selected by early stopping on the k-matched validation "
         "split (what the paper analyses); 'final' = the last epoch trained before early stopping "
         f"ended the run. 'Loss < {LOSS_ZERO}' = first epoch whose mean training loss is below "
         f"{LOSS_ZERO}.", "", n5_note(), "",
         f"| track | k | best epoch | final epoch | first epoch with loss < {LOSS_ZERO} | displacement at best | "
         "displacement at final | best minus final gate mean | mean abs per-dim displacement, best | "
         "same, final |", "|" + " --- |" * 10]
    for r in rows:
        L.append("| " + " | ".join([
            r["track"], r["k"], agg(r["best_epoch"], "{:.1f}"), agg(r["final_epoch"], "{:.1f}"),
            agg(r["loss_zero_epoch"], "{:.1f}"), agg(r["disp_best"]), agg(r["disp_final"]),
            agg(r["diff"]), agg(r["abs_dim_best"]), agg(r["abs_dim_final"])]) + " |")
    OUT.write_bytes(("\n".join(L) + "\n").encode("utf-8"))
    print("\n".join(L))


if __name__ == "__main__":
    main()
