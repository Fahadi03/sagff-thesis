"""§12 extension, step 2: frozen XLM-R embeddings for bnintent30-es and bnintent30-hi.

Same encoder, pinned revision, mean pooling and max length (128) as the main grid
(src/embeddings.py, unchanged), written to a SEPARATE cache, data/extension/cache/,
in the same format as scripts/cache_embeddings.py (matrix + sidecar). data/cache/ is
never touched. Covers every uid of the extension manifest (the 4,096 clean uids).
Idempotent: an up-to-date cache is not rebuilt.

Writes results/extension/embeddings.md: per track the longest tokenised utterance and
the number of truncated utterances (§12: "any truncation is reported"), with en and bn
from the main caches for reference.

Usage (from the repository root):  python scripts/extension_embed.py
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.embeddings import (ENCODER, MAX_LENGTH, POOLING, REVISION, cache_paths,  # noqa: E402
                            encode, sha256_file, texts_sha256)
from src.extension import CACHE_DIR, LANGS, SPLIT_BASE, TRACK, load_translations  # noqa: E402

OUT = ROOT / "results" / "extension" / "embeddings.md"


def main() -> None:
    manifest = json.loads((SPLIT_BASE / "manifest.json").read_text(encoding="utf-8"))
    rows = []
    for lang in LANGS:
        track = TRACK[lang]
        uids = sorted({u for e in manifest["splits"] if e["track"] == track for us in e["uids"].values() for u in us})
        tr = load_translations(lang)
        texts = [tr[u] for u in uids]
        npy, sidecar = cache_paths(track, CACHE_DIR)
        meta = json.loads(sidecar.read_text(encoding="utf-8")) if sidecar.exists() else {}
        fresh = (npy.exists() and meta.get("revision") == REVISION and meta.get("max_length") == MAX_LENGTH
                 and meta.get("uids") == uids and meta.get("texts_sha256") == texts_sha256(uids, texts)
                 and meta.get("sha256") == sha256_file(npy))
        if not fresh:
            t0 = time.time()
            X, truncated, env = encode(texts)
            npy.parent.mkdir(parents=True, exist_ok=True)
            np.save(npy, X)
            meta = {"track": track, "encoder": ENCODER, "revision": REVISION, "pooling": POOLING,
                    "max_length": MAX_LENGTH, "n": len(uids), "dim": int(X.shape[1]), "truncated": truncated,
                    "texts_sha256": texts_sha256(uids, texts), "sha256": sha256_file(npy),
                    "wall_clock_s": round(time.time() - t0, 1), **env, "frozen": True, "fit_on_dataset": False,
                    "note": "R1b: frozen encoder, no parameter estimated from this dataset; §12 extension cache",
                    "uids": uids}
            sidecar.write_text(json.dumps(meta, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
        print(f"{track}: n {meta['n']}, max tokens {meta['max_tokens_seen']}, truncated {meta['truncated']}, "
              f"{'built' if not fresh else 'up to date'}")
        rows.append(meta)
    ref = [json.loads(cache_paths(t)[1].read_text(encoding="utf-8")) for t in ("bnintent30-en", "bnintent30-bn")]
    L = ["# Extension: frozen XLM-R embeddings (docs/PROTOCOL.md §12)", "",
         "Generated by `python scripts/extension_embed.py`. Do not edit by hand. Numbers only.", "",
         f"Encoder `{ENCODER}` at revision `{REVISION}`, {POOLING} pooling, max length {MAX_LENGTH} tokens, "
         "frozen; the same settings as the main grid. es and hi caches are in `data/extension/cache/` "
         "(gitignored); en and bn are the main caches, shown for reference.", "",
         "| track | utterances | longest tokenised utterance (tokens) | truncated at max length | cache sha256 |",
         "| --- | --- | --- | --- | --- |"]
    for m in ref + rows:
        L.append(f"| {m['track']} | {m['n']} | {m['max_tokens_seen']} | {m['truncated']} | `{m['sha256']}` |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
