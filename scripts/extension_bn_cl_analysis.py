"""§12 Bangla translation-method control (amendment 2026-11-12): the registered analysis.

Reads the 40 bn-cl runs in results/extension/runs/ (track bnintent30-bn-cl) and, read-only,
the es/hi runs there and the en/bn runs in results/runs/. Writes NEW tables only
(results/tables/T9_*); no existing table, figure or run is touched (src.analysis reads only
results/runs/; scripts/extension_analysis.py reads only the es/hi runs).

  E4 (primary, a single test): paired test Macro-F1 difference sagff - baseline on bn-cl over
     k in {5, 10} x 5 seeds (n = 10), two-sided Wilcoxon (zeros dropped), alpha 0.05, no
     multiplicity adjustment; observed direction by the §11 item 4 rule; registered
     interpretation. The same statistic on the original bn runs, for reference.  -> T9a_bn_cl_e4.md
  Descriptive:
     Spearman rho(k rank, sagff gate displacement), bn-cl with bn for reference -> T9b_bn_cl_gate.md
     baseline test Macro-F1 at k = 5: bn-cl, bn, en, es, hi                    -> T9c_bn_cl_baseline_k5.md
     test Macro-F1 of both heads per k, bn-cl next to bn                       -> T9d_bn_cl_macro_f1.md
     rescoring without test rows colliding with the run's training subset
     (amendment 2026-11-09); E4 recomputed if any collision exists            -> T9e_bn_cl_rescoring.md

Usage (from the repository root):  python scripts/extension_bn_cl_analysis.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.analysis import ALPHA, fmt_p, msd, observed, spearman, wilcoxon  # noqa: E402
from src.extension import (CONTROL, CONTROL_SPLIT_BASE, E1_KS, HEADS, K_RANK, KS, RUN_DIR, SEEDS,  # noqa: E402
                           TRACK, colliding_test_uids, read_jsonl)
from src.train import macro_f1_acc  # noqa: E402

TABLES = ROOT / "results" / "tables"
MAIN_RUNS = ROOT / "results" / "runs"
TRACK_OF = {"en": "bnintent30-en", "bn": "bnintent30-bn", "es": TRACK["es"], "hi": TRACK["hi"], CONTROL: TRACK[CONTROL]}
HEADER = ("Generated by `python scripts/extension_bn_cl_analysis.py`. Do not edit by hand. docs/PROTOCOL.md §12, "
          "amendment 2026-11-12 (Bangla translation-method control, registered before any translation) and note "
          "2026-11-13. bn: the dataset's Google translation, reviewed by its authors. bn-cl: the same sentences in "
          "Bangla written by Claude (Fable 5.2) from English only, not reviewed.")


def load() -> tuple[dict, list[dict]]:
    """{(lang, k, seed, head): log} for ok runs of every track used here, and the bn-cl logs."""
    R, cl = {}, []
    by_track = {v: k for k, v in TRACK_OF.items()}
    for p in sorted(RUN_DIR.glob("*.json")):
        log = json.loads(p.read_text(encoding="utf-8"))
        lang = by_track.get(log["spec"]["track"])
        if lang == CONTROL:
            cl.append(log)
        if lang and log["status"] == "ok":
            R[(lang, log["spec"]["k"], log["spec"]["seed"], log["spec"]["condition"])] = log
    for lang in ("en", "bn"):
        for k in KS:
            for s in SEEDS:
                for h in HEADS:
                    log = json.loads((MAIN_RUNS / f"{TRACK_OF[lang]}__k{k}__seed{s}__{h}.json").read_text(encoding="utf-8"))
                    if log["status"] == "ok":
                        R[(lang, k, s, h)] = log
    return R, cl


def f1(log: dict) -> float:
    return log["metrics"]["test"]["macro_f1"]


def disp(log: dict) -> float:
    return log["gate"]["gate_displacement"]["mean"]


def e4(score, lang: str) -> dict:
    """The E4 statistic for `lang` with `score(lang, k, seed, head)`: a single test, no adjustment."""
    x = [score(lang, k, s, "sagff") for k in E1_KS for s in SEEDS]
    y = [score(lang, k, s, "baseline") for k in E1_KS for s in SEEDS]
    r = {"lang": lang, **wilcoxon(x, y)}
    r["observed"] = observed(r)
    r["sig_pos"] = r["p"] < ALPHA and r["observed"] == "> 0"
    return r


def interpretation(r: dict) -> str:
    if r["sig_pos"]:
        return "Significantly positive: the Bangla gain is not specific to the Google translation."
    neg = r["p"] < ALPHA and r["observed"] == "< 0"
    return (("Significantly negative (reported as observed); for the interpretation it counts as not significantly "
             "positive: " if neg else "Not significantly positive: ") + "the gain may depend on the Google-translated text.")


def e4_table(rows: list[tuple[str, dict]]) -> list[str]:
    L = ["| track | role | n pairs | n non-zero | W | median paired difference | rank-biserial | p | observed direction "
         "| significantly positive |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for role, r in rows:
        L.append(f"| {r['lang']} | {role} | {r['n']} | {r['n_nonzero']} | {r['statistic']:.1f} | {r['median_diff']:+.4f} | "
                 f"{r['rank_biserial']:+.3f} | {fmt_p(r['p'])} | {r['observed']} | {'yes' if r['sig_pos'] else 'no'} |")
    return L


def write(name: str, lines: list[str]) -> None:
    (TABLES / name).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote results/tables/{name}")


def main() -> None:
    R, cl = load()
    expected = len(HEADS) * len(KS) * len(SEEDS)
    missing = [(k, s, h) for h in HEADS for k in KS for s in SEEDS if (CONTROL, k, s, h) not in R]
    if missing:
        sys.exit(f"STOP: {len(missing)} of {expected} bn-cl runs missing or failed, e.g. {missing[:3]}")
    accounting = (f"Runs: {len(cl)} bn-cl runs in `results/extension/runs/` ({sum(l['status'] == 'ok' for l in cl)} ok, "
                  f"{sum(l['status'] == 'failed' for l in cl)} failed; {expected} registered), summed run wall-clock "
                  f"{sum(l['wall_clock_s'] for l in cl) / 60:.1f} min. bn and en runs are read from `results/runs/`, es "
                  "and hi from `results/extension/runs/`; all unchanged.")

    score = lambda lang, k, s, h: f1(R[(lang, k, s, h)])
    r_cl, r_bn = e4(score, CONTROL), e4(score, "bn")
    write("T9a_bn_cl_e4.md", [
        "# T9a. Bangla control E4 (primary): sagff - baseline test Macro-F1 on bn-cl, k in {5, 10}", "", HEADER, "",
        accounting, "",
        "Paired over (k, seed) for k in {5, 10} and seeds 13, 42, 87, 100, 2026 (n = 10); two-sided Wilcoxon "
        "signed-rank (`scipy.stats.wilcoxon`, zero_method='wilcox'); alpha 0.05; a single test, no multiplicity "
        "adjustment. Observed direction: sign of the matched-pairs rank-biserial correlation, 'ambiguous' if the "
        "median paired difference has the other sign (§11 item 4). Significantly positive: p < 0.05 with a positive "
        "observed direction. The bn row is the same statistic on the original Bangla runs of the main grid, for "
        "reference; it is not part of the registered test.", ""]
        + e4_table([("registered test (E4)", r_cl), ("reference, not a test", r_bn)])
        + ["", "**Registered interpretation (§12, amendment 2026-11-12):** " + interpretation(r_cl)])

    L = ["# T9b. Bangla control (descriptive): Spearman rho(k, sagff gate displacement)", "", HEADER, "",
         "Gate displacement at the epoch selected by early stopping (the primary readout of §10), sagff head, test "
         "split; k as ranks 5 < 10 < 20 < full; n = 20. Not part of any test family. bn is S1 of the main grid, "
         "recomputed for reference. Right: mean ± SD of the displacement over seeds.", "",
         "| track | n | rho | p (unadjusted) | k=5 | k=10 | k=20 | k=full |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for lang in (CONTROL, "bn"):
        r = spearman([K_RANK[k] for k in KS for s in SEEDS], [disp(R[(lang, k, s, "sagff")]) for k in KS for s in SEEDS])
        L.append(f"| {lang}{' (reference)' if lang == 'bn' else ''} | {r['n']} | {r['rho']:+.3f} | {fmt_p(r['p'])} | "
                 + " | ".join(msd([disp(R[(lang, k, s, 'sagff')]) for s in SEEDS], "{:+.4f}") for k in KS) + " |")
    write("T9b_bn_cl_gate.md", L)

    L = ["# T9c. Bangla control (descriptive): baseline test Macro-F1 at k = 5", "", HEADER, "",
         "The encoder-only `baseline` head at k = 5, mean ± SD (min-max) over the five seeds.", "",
         "| track | baseline Macro-F1, k=5 | min-max | source |", "| --- | --- | --- | --- |"]
    for lang in (CONTROL, "bn", "en", "es", "hi"):
        v = [f1(R[(lang, "5", s, "baseline")]) for s in SEEDS]
        L.append(f"| {lang} | {msd(v)} | {min(v):.3f}-{max(v):.3f} | "
                 f"{'results/runs/' if lang in ('en', 'bn') else 'results/extension/runs/'} |")
    write("T9c_bn_cl_baseline_k5.md", L)

    L = ["# T9d. Bangla control (descriptive): test Macro-F1 of baseline and sagff per k", "", HEADER, "",
         "Mean ± SD over the five seeds; difference paired by seed (sagff - baseline), with the number of seeds (of 5) "
         "in which it is positive. Descriptive: per-cell tests cannot reach alpha 0.05 with five pairs.", "",
         "| track | k | baseline | sagff | sagff - baseline | seeds positive |", "| --- | --- | --- | --- | --- | --- |"]
    for lang in (CONTROL, "bn"):
        for k in KS:
            b = [f1(R[(lang, k, s, "baseline")]) for s in SEEDS]
            g = [f1(R[(lang, k, s, "sagff")]) for s in SEEDS]
            d = [x - y for x, y in zip(g, b)]
            L.append(f"| {lang} | {k} | {msd(b)} | {msd(g)} | {msd(d, '{:+.3f}')} | {sum(v > 0 for v in d)} |")
    write("T9d_bn_cl_macro_f1.md", L)

    manifest = json.loads((CONTROL_SPLIT_BASE / "manifest.json").read_text(encoding="utf-8"))
    entry = {(e["k"], e["seed"]): e for e in manifest["splits"]}
    n_classes = len(manifest["label_names"][TRACK[CONTROL]])
    rescored, n_coll = {}, {}
    for k in KS:
        for s in SEEDS:
            base = CONTROL_SPLIT_BASE / entry[(k, s)]["path"]
            train, test = read_jsonl(base / "train.jsonl"), read_jsonl(base / "test.jsonl")
            coll = set(colliding_test_uids([r["text"] for r in train], [(r["uid"], r["text"]) for r in test]))
            n_coll[(k, s)] = len(coll)
            keep = [r for r in test if r["uid"] not in coll]
            for h in HEADS:
                pred = R[(CONTROL, k, s, h)]["metrics"]["test"]["predictions"]
                assert set(pred) == {r["uid"] for r in test}
                rescored[(CONTROL, k, s, h)] = macro_f1_acc([r["label_id"] for r in keep],
                                                            [pred[r["uid"]] for r in keep], n_classes)["macro_f1"]
    L = ["# T9e. Bangla control: rescoring sensitivity analysis (§12 amendment 2026-11-09)", "", HEADER, "",
         "A test row collides if its §3.3 dedup key, on the bn-cl text, equals the key of any row in the run's own "
         "training subset. The same trained models and their saved predictions; test Macro-F1 recomputed without the "
         "colliding rows; E4 recomputed on these scores. No model is retrained. Applicable only if at least one run "
         "has a colliding test row.", "",
         "Colliding test rows per run, mean (min-max) over seeds (test split: 856 rows):", "",
         "| track | k=5 | k=10 | k=20 | k=full |", "| --- | --- | --- | --- | --- |",
         f"| {CONTROL} | " + " | ".join(f"{np.mean([n_coll[(k, s)] for s in SEEDS]):.1f} "
                                    f"({min(n_coll[(k, s)] for s in SEEDS)}-{max(n_coll[(k, s)] for s in SEEDS)})"
                                    for k in KS) + " |", ""]
    if not any(n_coll.values()):
        L.append("No colliding test row in any run: the sensitivity analysis is not applicable.")
    else:
        rr = e4(lambda lang, k, s, h: rescored[(lang, k, s, h)], CONTROL)
        L += ["E4 on the rescored Macro-F1 (same test and n as T9a):", ""] + e4_table([("rescored E4", rr)])
        L += ["", "**Registered interpretation on the rescored scores:** " + interpretation(rr)]
    write("T9e_bn_cl_rescoring.md", L)


if __name__ == "__main__":
    main()
