@pytest.mark.parametrize("track", TRACKS)
def test_kshot_counts_and_full_way_test(track, split_files, manifest):
    """Train has <= k rows per class (exactly min(k, available)); test has ALL classes (R5)."""
    n_classes = len(manifest["label_names"][track])
    full_train = {tuple(sorted(r["uid"] for r in files["train"]))
                  for (t, k, s), files in split_files.items() if t == track and k == "full"}
    assert len(full_train) == 1, f"[{track}] k=full train differs in content between seeds"
    available = Counter(r["label_id"] for (t, k, s), f in split_files.items()
                        if t == track and k == "full" and s == 13 for r in f["train"])
    problems = []
    for (t, k, seed), files in split_files.items():
        if t != track:
            continue
        per_class = Counter(r["label_id"] for r in files["train"])
        if k != "full":
            for lid in range(n_classes):
                want = min(int(k), available[lid])
                if per_class[lid] > int(k) or per_class[lid] != want:
                    problems.append(f"k={k} seed={seed}: class {lid} has {per_class[lid]} train "
                                    f"rows (expected {want})")
        missing = set(range(n_classes)) - {r["label_id"] for r in files["test"]}
        if missing:
            problems.append(f"k={k} seed={seed}: test is missing classes {sorted(missing)}")
    check(problems, f"[{track}] k-shot / full-way violations")


