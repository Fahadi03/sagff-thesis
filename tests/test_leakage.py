@pytest.mark.parametrize("track", TRACKS)
def test_splits_disjoint_by_text(track, split_files):
    """Train, val and test share zero utterance texts, for every (k, seed)."""
    problems = []
    for (t, k, seed), files in split_files.items():
        if t != track:
            continue
        texts = {s: {norm_text(r["text"]): r["uid"] for r in rows} for s, rows in files.items()}
        for a, b in combinations(("train", "val", "test"), 2):
            for text in sorted(texts[a].keys() & texts[b].keys()):
                problems.append(f"k={k} seed={seed}: {a} uid {texts[a][text]} and {b} uid "
                                f"{texts[b][text]} share the text {text!r}")
    check(problems, f"[{track}] text overlap between splits")


