def test_make_splits_reproduces_manifest(tmp_path, manifest, built):
    """Re-running make_splits gives byte-identical files matching the manifest sha256."""
    from scripts.make_splits import compare, generate
    regenerated = generate(tmp_path, tracks=built[0])
    problems = compare(regenerated, manifest)
    for e in regenerated["splits"]:
        for s in ("train", "val", "test"):
            new = (tmp_path / e["path"] / f"{s}.jsonl").read_bytes()
            on_disk = (SPLITS_DIR / e["path"] / f"{s}.jsonl").read_bytes()
            if new != on_disk:
                problems.append(f"{e['path']}/{s}.jsonl: regenerated bytes differ from data/splits")
            if hashlib.sha256(new).hexdigest() != e["sha256"][s]:
                problems.append(f"{e['path']}/{s}.jsonl: sha256 does not match its own record")
    check(problems, "make_splits.py is not reproducible")


